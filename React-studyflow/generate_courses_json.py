def add_glossary_refs(text):
    """Add [[term_id|Display Text]] glossary references to text."""
    # Sort glossary terms by length (longest first) to avoid partial replacements
    sorted_terms = sorted(GLOSSARY_MAP.keys(), key=len, reverse=True)
    
    result = text
    for term_text in sorted_terms:
        term_id = GLOSSARY_MAP[term_text]
        # Create regex that matches word boundaries (case-insensitive)
        pattern = r'(?i)\b' + re.escape(term_text) + r'\b'
        replacement = f'[[{term_id}|{term_text}]]'
        result = re.sub(pattern, replacement, result)
    
    return result

