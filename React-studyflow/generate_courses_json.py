def build_course_from_md(course_dir, course_id, course_title, course_desc, topic_files):
    """Build a course object from .md files."""
    topics = []
    for topic_file, topic_id, topic_title in topic_files:
        md_path = course_dir / topic_file
        content = load_md_file(md_path)
        if content is None:
            print(f"Warning: {md_path} not found")
            continue
        
        # Add glossary references
        enhanced_content = add_glossary_refs(content)
        
        topics.append({
            "id": topic_id,
            "title": topic_title,
            "notes": enhanced_content
        })
    
    return {
        "id": course_id,
        "title": course_title,
        "description": course_desc,
        "topics": topics
    }

